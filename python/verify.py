def check(name: str, thunk, expected, normalize=None) -> None:
    try:
        actual = thunk()
        if normalize is not None:
            actual = normalize(actual)
            expected_value = normalize(expected)
        else:
            expected_value = expected
        if isinstance(expected_value, float) or isinstance(actual, float):
            ok = (
                isinstance(actual, (int, float))
                and abs(float(actual) - float(expected_value)) < 1e-9
            )
        else:
            ok = actual == expected_value
        detail = "" if ok else f"expected {expected_value!r}, got {actual!r}"
    except RecursionError:
        ok, detail = False, "RecursionError (runaway recursion)"
    except Exception as exc:  # noqa: BLE001 - a crash is a failing check
        ok, detail = False, f"{type(exc).__name__}: {exc}"
    _results.append((_current[0], f"{_current[1]} / {name}", ok, detail))


