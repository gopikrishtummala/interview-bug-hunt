def _lfu_scenario() -> list[int]:
    cache = H.LFUCache(2)
    out: list[int] = []
    cache.put(1, 1)
    cache.put(2, 2)
    out.append(cache.get(1))  # 1, and bumps key 1 to count 2
    cache.put(3, 3)  # evicts key 2 (count 1)
    out.append(cache.get(2))  # -1
    out.append(cache.get(3))  # 3
    cache.put(4, 4)  # evicts key 1? no - key 1 has count 2, key 3 has count 2
    out.append(cache.get(1))  # -1
    out.append(cache.get(3))  # 3
    out.append(cache.get(4))  # 4
    return out


def _lfu_overwrite() -> int:
    cache = H.LFUCache(2)
    cache.put(1, 1)
    cache.put(2, 2)
    cache.put(1, 10)  # an overwrite counts as a use
    cache.put(3, 3)  # so key 2 is the least frequent and goes
    return cache.get(2)


