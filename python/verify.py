def _median_scenario() -> list[float]:
    finder = H.MedianFinder()
    out: list[float] = []
    finder.add_num(1)
    finder.add_num(2)
    out.append(finder.find_median())
    finder.add_num(3)
    out.append(finder.find_median())
    return out


def _median_descending() -> float:
    finder = H.MedianFinder()
    for value in (5, 4, 3, 2, 1):
        finder.add_num(value)
    return finder.find_median()


