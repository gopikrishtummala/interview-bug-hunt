def main() -> int:
    by_problem: dict[str, list[tuple[str, bool, str]]] = {}
    for number, name, ok, detail in _results:
        by_problem.setdefault(number, []).append((name, ok, detail))

    passed = sum(1 for *_, ok, _d in _results if ok)
    failed = len(_results) - passed
    broken: list[str] = []

    for number in sorted(by_problem):
        rows = by_problem[number]
        title = rows[0][0].split(" / ")[0]
        bad = [r for r in rows if not r[1]]
        if bad:
            broken.append(f"{number} {title}")
        if QUIET:
            mark = "FAIL" if bad else "pass"
            print(f"  {mark}  {number} {title}  ({len(rows) - len(bad)}/{len(rows)})")
            continue
        print(f"\n== {number} {title} ==")
        for name, ok, detail in rows:
            case = name.split(" / ", 1)[1]
            if ok:
                print(f"  pass  {case}")
            else:
                print(f"  FAIL  {case}  ->  {detail}")

    print()
    print(f"checks passed: {passed}   failed: {failed}")
    print(f"problems clean: {50 - len(broken)}/50   still broken: {len(broken)}")
    if broken:
        print()
        print("Problems with at least one failing check:")
        for item in broken:
            print(f"  - {item}")
        return 1
    print("All green. Now explain each bug you fixed and how you spotted it.")
    return 0


